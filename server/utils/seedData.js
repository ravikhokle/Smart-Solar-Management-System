export const seedDatabase = async () => {
  try {
    const userCount = await User.countDocuments();
    if (userCount === 0) {
      console.log('[Seed] Seeding default Users...');
      for (const u of mockData.users) {
        await User.create(u);
      }
    }

    const customerCount = await Customer.countDocuments();
    if (customerCount === 0) {
      console.log('[Seed] Seeding default Customers...');
      await Customer.insertMany(mockData.customers);
    }

    const projectCount = await Project.countDocuments();
    if (projectCount === 0) {
      console.log('[Seed] Seeding default Projects...');
      await Project.insertMany(mockData.projects);
    }

    const inventoryCount = await Inventory.countDocuments();
    if (inventoryCount === 0) {
      console.log('[Seed] Seeding default Inventory items...');
      await Inventory.insertMany(mockData.inventory);
    }

    const surveyCount = await Survey.countDocuments();
    if (surveyCount === 0) {
      console.log('[Seed] Seeding default Surveys...');
      await Survey.insertMany(mockData.surveys);
    }

    console.log('[Seed] Database initialization check complete.');
  } catch (error) {
    console.warn('[Seed] Warning during initial DB seed:', error.message);
  }
};
