import PDFDocument from 'pdfkit';
import { getSettings } from '../models/Setting.js';

const ORANGE = '#F47C45';
const CHARCOAL = '#29343A';
const MUTED = '#7C817F';

function money(n) {
  return `INR ${Number(n || 0).toFixed(2)}`;
}

export async function streamPdf(res, filename, draw) {
  const settings = await getSettings();
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
  const doc = new PDFDocument({ size: 'A4', margin: 48 });
  doc.pipe(res);
  await drawDocument(doc, settings, draw);
  doc.end();
}

export async function createPdfBuffer(draw) {
  const settings = await getSettings();
  const doc = new PDFDocument({ size: 'A4', margin: 48 });
  const chunks = [];
  return new Promise((resolve, reject) => {
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    drawDocument(doc, settings, draw).then(() => doc.end()).catch(reject);
  });
}

async function drawDocument(doc, settings, draw) {
  doc.rect(0, 0, doc.page.width, 64).fill(CHARCOAL);
  doc.fillColor('#FFFFFF').fontSize(16).text(settings.companyName || 'HeliosFlow Solar', 48, 24);
  doc.fillColor(ORANGE).fontSize(10).text('Solar Installation Management', 48, 44);
  doc.fillColor(CHARCOAL);
  await draw(doc, settings);
  doc.moveDown(2);
  doc.fontSize(8).fillColor(MUTED).text('Generated by HeliosFlow. Figures reflect stored business records.', 48);
}

export function drawKeyValues(doc, rows) {
  doc.fontSize(10).fillColor(CHARCOAL);
  rows.forEach(([k, v]) => {
    doc.text(`${k}: ${v ?? '—'}`, { continued: false });
  });
}

export function drawTable(doc, headers, rows) {
  const startX = 48;
  let y = doc.y + 8;
  const colW = (doc.page.width - 96) / headers.length;
  doc.fontSize(9).fillColor(ORANGE);
  headers.forEach((h, i) => doc.text(h, startX + i * colW, y, { width: colW }));
  y += 16;
  doc.fillColor(CHARCOAL);
  rows.forEach((row) => {
    if (y > 740) {
      doc.addPage();
      y = 72;
    }
    row.forEach((cell, i) => doc.text(String(cell ?? ''), startX + i * colW, y, { width: colW }));
    y += 16;
  });
  doc.y = y;
}

export { money };
